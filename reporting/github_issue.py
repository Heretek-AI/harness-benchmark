"""Automated GitHub Issue Publisher with Date Labels for Harness Benchmark 2.0."""

from __future__ import annotations

import datetime
import subprocess

from core.types import BenchmarkReport
from reporting.ab_comparator import ABComparator
from reporting.scorecard import ScorecardGenerator


class GitHubIssuePublisher:
    """Formats and publishes date-labeled GitHub issue reports."""

    @staticmethod
    def build_issue_content(
        report: BenchmarkReport,
        target_date: str | None = None,
    ) -> tuple[str, str, list[str]]:
        """Build title, body, and labels for a date-labeled GitHub issue."""
        date_str = target_date or datetime.date.today().strftime("%Y-%m-%d")
        title = f"[Benchmark Report] {date_str} — AI Coding Agent Arena & Evaluation"
        labels = ["benchmark", "automated-report", date_str]

        # 1. Header & Leaderboard
        body_parts = [
            f"# 📊 Automated Benchmark Arena Report — `{date_str}`",
            "",
            "> Automated evaluation matrix report generated by [Harness Benchmark](https://github.com/Heretek-AI/harness-benchmark).",
            "",
            ScorecardGenerator.render_markdown_leaderboard(report),
            "",
        ]

        # 2. A/B Comparisons (if baseline/treatment pairs exist)
        summaries = report.summaries
        baselines = [s for s in summaries if not s.plugins and not s.mcp_servers]
        treatments = [s for s in summaries if s.plugins or s.mcp_servers]
        ab_results = []

        for b in baselines:
            for t in treatments:
                if b.harness == t.harness and b.benchmark == t.benchmark:
                    ab_results.append(ABComparator.compare_cells(b, t))

        if ab_results:
            body_parts.extend(
                [
                    ABComparator.render_ab_markdown_table(ab_results),
                    "",
                ]
            )

        # 3. Per-Task Execution Breakdown
        body_parts.extend(
            [
                ScorecardGenerator.render_task_drilldown_table(report),
                "",
            ]
        )

        # 4. Collapsible Failure Diagnostics
        failed_tasks = [r for r in report.results if not r.passed]
        if failed_tasks:
            body_parts.extend(
                [
                    "### 🔍 Detailed Failure Inspection",
                    "",
                    "<details>",
                    f"<summary>Click to view diagnostics for {len(failed_tasks)} failed tasks</summary>",
                    "",
                ]
            )
            for r in failed_tasks:
                body_parts.extend(
                    [
                        f"#### ❌ Task `{r.task_id}` ({r.harness} / {r.benchmark})",
                        f"- **Duration**: {r.duration_seconds:.2f}s | **Exit Code**: {r.exit_code}",
                    ]
                )
                if r.oracle_log:
                    body_parts.extend(
                        [
                            "**Oracle Error Log**:",
                            f"```text\n{r.oracle_log.strip()}\n```",
                        ]
                    )
                if r.stderr:
                    body_parts.extend(
                        [
                            "**Stderr Log**:",
                            f"```text\n{r.stderr.strip()[:2000]}\n```",
                        ]
                    )
                body_parts.append("")
            body_parts.extend(["</details>", ""])

        # 5. Footer
        body_parts.extend(
            [
                "---",
                f"*Report generated at `{datetime.datetime.now(datetime.UTC).isoformat()}` by `harness-benchmark`.*",
            ]
        )

        return title, "\n".join(body_parts), labels

    @classmethod
    def publish_issue(
        cls,
        report: BenchmarkReport,
        repo: str | None = None,
        target_date: str | None = None,
    ) -> str | None:
        """Publish the benchmark report as a GitHub Issue via `gh issue create`."""
        title, body, labels = cls.build_issue_content(report, target_date)

        cmd = ["gh", "issue", "create", "--title", title, "--body", body]
        for lbl in labels:
            cmd.extend(["--label", lbl])
        if repo:
            cmd.extend(["--repo", repo])

        try:
            proc = subprocess.run(cmd, capture_output=True, text=True, check=True)
            issue_url = proc.stdout.strip()
            return issue_url
        except Exception:
            # If label does not exist, retry without labels or log
            try:
                fallback_cmd = ["gh", "issue", "create", "--title", title, "--body", body]
                if repo:
                    fallback_cmd.extend(["--repo", repo])
                proc = subprocess.run(fallback_cmd, capture_output=True, text=True, check=True)
                return proc.stdout.strip()
            except Exception:
                return None
